const TRANSICION = { corporal: 0, ligero: 10, pesas: 15, barra: 20 };

function ex(d) {
  const equipo = d.equipo ?? ["corporal"];
  return {
    id: d.id,
    nombre: d.nombre,
    tipo: d.tipo ?? "principal",            // calentamiento | principal | estiramiento
    musculo: d.musculo,
    secundarios: d.secundarios ?? [],
    patron: d.patron ?? "aislamiento",
    equipo,
    lugar: equipo.some(e => e === "maquina" || e === "polea") ? "gym" : "ambos",
    zona: d.zona ?? null,                   // superior | inferior | completo (calentamiento y estiramiento)
    nivel: d.nivel ?? 1,
    facil: d.facil ?? null,
    dificil: d.dificil ?? null,
    modo: d.modo ?? "tiempo",
    unilateral: d.unilateral ?? false,
    carga: d.carga ?? equipo.some(e => ["barra", "mancuernas", "kettlebell", "maquina", "polea", "balon"].includes(e)),
    tecnica: d.tecnica,
    respiracion: d.respiracion,
    error: d.error,
    demostracion: d.demostracion ?? null,
    camara: d.camara ?? null,               // id de la regla de cámara (sentadilla, triceps…) cuando existe
    transicion: d.transicion ?? (equipo.includes("barra") ? TRANSICION.barra
      : equipo.some(e => ["mancuernas", "kettlebell", "maquina", "polea"].includes(e)) ? TRANSICION.pesas
      : equipo.some(e => ["banco", "balon", "dominadas"].includes(e)) ? TRANSICION.ligero
      : TRANSICION.corporal),
  };
}

